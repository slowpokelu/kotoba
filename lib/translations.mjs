export function translate(text, language) {
  if (language !== 'en') return text;
  if (english[text] !== undefined) return english[text];
  return String(text)
    .replace(
      /^ひらがな([3-6])文字で入力してください。$/,
      'Enter exactly $1 hiragana.',
    )
    .replace(/^ひらがな([3-6])文字$/, '$1 hiragana')
    .replace(/^(\d+)文字まで入力できます。$/, 'You can enter up to $1 kana.')
    .replace(/^([3-6])文字$/, '$1 kana')
    .replace(/^正解！ (\d+)回で見つけました。$/, 'Solved in $1 guesses!')
    .replace(
      /^答えは「(.+)」と「(.+)」でした。$/,
      'The answers were $1 and $2.',
    )
    .replace(
      /^答えは「(.+)」「(.+)」「(.+)」でした。$/,
      'The answers were $1, $2 and $3.',
    )
    .replace(/^答えは「(.+)」でした。$/, 'The answer was $1.')
    .replace(/^(\d+) \/ (\d+) 回で正解。$/, 'Solved in $1 / $2 guesses.')
    .replace(/^第(\d+)回答：/, 'Guess $1: ')
    .replace(/^第(\d+)回答$/, 'Guess $1')
    .replace(/、辞書で見る$/, ', look up on Jisho')
    .replace(/(\d+)文字目 /g, 'Tile $1: ')
    .replace(/似たかなが同じ位置/g, 'variant in this spot')
    .replace(/似たかなが別の位置/g, 'variant elsewhere')
    .replace(/位置も一致/g, 'correct spot')
    .replace(/別の位置/g, 'wrong spot')
    .replace(/含まれない/g, 'not in word')
    .replace(/^(\d+)回で正解：(\d+)問$/, '$2 wins in $1 guesses')
    .replace(/^(\d+)語$/, '$1 words')
    .replace(/^(\d+)点$/, '$1 points')
    .replace(/^(\d+) \/ (\d+)語$/, '$1 of $2 words')
    .replace(/^「(.+)」まで (\d+)点$/, '$2 points to $1')
    .replace(/^真ん中の「(.+)」を使ってください。$/, 'Use the centre kana $1.')
    .replace(/^いいね！ \+(\d+)$/, 'Nice! +$1')
    .replace(/^全部使った！ \+(\d+)$/, 'All seven! +$1')
    .replace(/^(\d+)手目$/, 'Guess $1')
    .replace(/^(\d+)手$/, '$1 guesses')
    .replace(/^(\d+)手で追い詰めました。$/, 'Cornered in $1 guesses.')
    .replace(/^最高 (\d+)$/, 'Best $1')
    .replace(/^「(.+)」から始まる言葉$/, 'A word starting with $1')
    .replace(
      /^「(.+)」から始まる言葉を答えてください。$/,
      'Your word must start with $1.',
    )
    .replace(
      /^「(.+)」から始まる言葉が見つかりません。あなたの勝ち！$/,
      'No word left starting with $1. You win!',
    )
    .replace(/^(\d+)文字目は「(.+)」です。$/, 'Tile $1 must be $2.')
    .replace(/^(\d+)文字目に「(.+)」は入りません。$/, "Tile $1 can't be $2.")
    .replace(
      /^(\d+)文字目は「(.+)」のどれかです。$/,
      'Tile $1 must be one of $2.',
    )
    .replace(/^「(.+)」から(\d+)つ使ってください。$/, 'Use $2 of $1.')
    .replace(/^「(.+)」のどれかを使ってください。$/, 'Use one of $1.')
    .replace(/^「(.+・.+)」は使えません。$/, 'None of $1 is in the word.')
    .replace(/^「(.+)」は使えません。$/, '$1 is not in the word.')
    .replace(/^「(.+・.+)」は1つだけです。$/, 'The word has only one of $1.')
    .replace(/^「(.+)」は1つだけです。$/, 'The word has only one $1.')
    .replace(/^「(.+)」は(\d+)つだけです。$/, 'The word has only $2 of $1.')
    .replace(/^「(.+)」を(\d+)つ使ってください。$/, 'Use $1 $2 times.')
    .replace(/^「(.+)」を使ってください。$/, 'Your guess must use $1.');
}
